/** One service of a Compose file: from its name to the next service or top-level key. */
function service(compose: string, name: string): string {
  const start = compose.indexOf(`\n  ${name}:\n`)
  expect(start, `service ${name}`).toBeGreaterThan(0)
  const rest = compose.slice(start + 1)
  const end = rest.slice(1).search(/\n {2}\S|\n\S/)
  return end < 0 ? rest : rest.slice(0, end + 1)
}

describe(CADDY_PUBLIC_PATH, () => {
  it('is up to date with src/lib/public-pages.ts and the approved texts', () => {
    expect(
      readFileSync(CADDY_PUBLIC_FILE, 'utf8'),
      'deploy/caddy/m2-public.caddy is out of date: run pnpm caddy:public',
    ).toBe(m2PublicCaddy())
    expect(m2PublicCaddy()).toMatch(/^# Generated by `pnpm caddy:public`.*do not edit it by hand/)
  })

  for (const [name, draft] of [
    ['now', undefined],
    ['every text approved', ALL_APPROVED],
  ] as const) {
    it(`opens only public addresses, never with the password’s file (${name})`, () => {
      const text = m2PublicCaddy(draft)
      // Nothing here asks for the password, serves files or goes anywhere but the app.
      expect(text).not.toMatch(/admin-auth|basic_auth|file_server|root \*/)
      const blocks = publicPostPaths(draft).length > 0 ? 3 : 2
      expect(text.match(/^@\w+ \{$/gm)).toHaveLength(blocks)
      expect(text.match(/^handle @\w+ \{$/gm)).toHaveLength(blocks)
      // Each matcher: its methods, its paths and the regexp on the raw address, nothing else.
      for (const block of ['m2Public', 'm2PublicFiles', 'm2PublicPost'].slice(0, blocks)) {
        const lines = matcherBody(text, block).split('\n').filter(Boolean)
        expect(lines[0], block).toBe(
          block === 'm2PublicPost' ? '\tmethod POST' : '\tmethod GET HEAD',
        )
        expect(lines.at(-1), block).toMatch(/^\tvars_regexp \{http\.request\.uri\} \^\S+\$$/)
        for (const line of lines.slice(1, -1)) expect(line, block).toMatch(/^\tpath \S/)
      }
      const get = matcherPaths(text, 'm2Public')
      expect(get).toEqual(publicGetPaths(draft))
      for (const path of get) {
        expect(path, path).not.toContain('*')
        expect(path, path).not.toMatch(/^\/(?:api|admin|basemap|m2|health)(?:\/|$)/)
      }
      // Next.js's own files by prefix, the logos each by name, as the folder holds them.
      expect(matcherPaths(text, 'm2PublicFiles')).toEqual(['/_next/static/*', ...brandFiles()])
      for (const path of brandFiles()) expect(isPublicAddress(path, draft), path).toBe(true)
      if (publicPostPaths(draft).length > 0) {
        expect(matcherPaths(text, 'm2PublicPost')).toEqual(publicPostPaths(draft))
      } else {
        // A matcher without paths would match every path.
        expect(text).not.toContain('@m2PublicPost')
      }
    })

    it(`lets only the exact spelling of each address through (${name})`, () => {
      const text = m2PublicCaddy(draft)
      const pages = rawAddress(text, 'm2Public')
      const files = rawAddress(text, 'm2PublicFiles')
      for (const path of publicGetPaths(draft)) {
        for (const query of ['', '?', '?token=abc%20def&x=1', '?utm_source=x']) {
          expect(pages.test(`${path}${query}`), `${path}${query}`).toBe(true)
        }
        expect(files.test(path), path).toBe(false)
      }
      for (const path of [
        ...brandFiles(),
        '/_next/static/chunks/3979yy9j2k--s.js',
        '/_next/static/chunks/a_b~c.js?dpl=x',
        '/_next/static/media/font.p.woff2',
        '/_next/static/Wm6lpgZ_Hh0Y8AsR8Rh_d/_buildManifest.js',
      ]) {
        expect(files.test(path), path).toBe(true)
        expect(pages.test(path), path).toBe(false)
      }
      for (const path of OTHER_SPELLINGS) {
        expect(pages.test(path), path).toBe(false)
        expect(files.test(path), path).toBe(false)
      }
      if (publicPostPaths(draft).length > 0) {
        const post = rawAddress(text, 'm2PublicPost')
        for (const path of publicPostPaths(draft)) expect(post.test(`${path}?x=1`), path).toBe(true)
        for (const path of [...OTHER_SPELLINGS, '/en/legal/DATA-REQUESTS/', '/en/about/']) {
          expect(post.test(path), path).toBe(false)
        }
      }
    })

    it(`marks the requests of pages and forms, and passes only the app's marked answers (${name})`, () => {
      const text = m2PublicCaddy(draft)
      for (const block of ['m2Public', 'm2PublicPost']) {
        if (block === 'm2PublicPost' && publicPostPaths(draft).length === 0) continue
        expect(handleBody(text, block), block).toBe(
          [
            `\trequest_header ${PUBLIC_MARK.name} ${PUBLIC_MARK.value}`,
            ...PLAIN_MISSING,
            ...ONLY_MARKED,
            '\t}',
            '',
          ].join('\n'),
        )
      }
      // Next.js's files and the logos carry no mark: they are the same in every image.
      expect(handleBody(text, 'm2PublicFiles')).toBe([...PLAIN_MISSING, '\t}', ''].join('\n'))
    })
  }
})

describe('deploy/Caddyfile: the site’s stage', () => {
  const caddyfile = read('deploy/Caddyfile')
  const site = caddyfile.slice(caddyfile.indexOf('\n{$SITE_DOMAIN} {'))

  it('has one snippet per stage: nothing for private, the generated file for m2', () => {
    const snippets = [...caddyfile.matchAll(/^\(stage-([a-z0-9]+)\) \{\n([\s\S]*?)^\}/gm)]
    expect(snippets.map((match) => match[1])).toEqual([...SITE_STAGES])
    const body = Object.fromEntries(snippets.map((match) => [match[1], match[2]!.trim()]))
    expect(body.private).toBe('')
    expect(body.m2).toBe(`import ${CADDY_PUBLIC_MOUNT}`)
  })

  it('imports the stage’s snippet in the site, private by default, before the catch-all', () => {
    expect(caddyfile.match(/import "?stage-/g)).toHaveLength(1)
    // Quoted: Caddy reads the whole value as one name, as the app does (src/lib/site-stage.ts), so
    // `m2 x` or `m2` with a comment after it names no snippet, and Caddy refuses to start.
    const at = site.indexOf('\timport "stage-{$SITE_STAGE:private}"\n')
    expect(at).toBeGreaterThan(0)
    // After the handles that keep their own rules (the health check, the basemap, the admin),
    // before the catch-all that asks for the password for everything else.
    expect(at).toBeGreaterThan(site.indexOf('handle @admin'))
    expect(at).toBeLessThan(site.lastIndexOf('\thandle {'))
    expect(site.slice(site.lastIndexOf('\thandle {'))).toMatch(
      /^\thandle \{\n\t\timport \/etc\/caddy\/admin-auth\.caddy\n\t\treverse_proxy app:3000\n\t\}/,
    )
    // Not in the www site, which only redirects.
    expect(caddyfile.slice(caddyfile.indexOf('\nwww.{$SITE_DOMAIN}'))).not.toContain('stage-')
  })
})

describe('deploy/compose.prod.yml and .env.example: the site’s stage', () => {
  const compose = read('deploy/compose.prod.yml')

  it('give Caddy and the app the same SITE_STAGE, unchanged, private by default', () => {
    // The same expression in both, so both read the same characters (no quotes, no trimming):
    // the app shows the M2 state only for exactly `m2`, and Caddy opens it only for exactly that.
    const lines = ['caddy', 'app'].map((name) =>
      service(compose, name)
        .split('\n')
        .filter((line) => /\bSITE_STAGE\b/.test(line) && !line.trim().startsWith('#')),
    )
    expect(lines).toEqual([
      ['      SITE_STAGE: ${SITE_STAGE:-private}'],
      ['      SITE_STAGE: ${SITE_STAGE:-private}'],
    ])
    expect(service(compose, 'db')).not.toContain('SITE_STAGE')
    expect(read('deploy/.env.example')).toMatch(/^SITE_STAGE=private$/m)
    expect(read('.env.example')).toMatch(/^# SITE_STAGE=private$/m)
  })

  it('give Caddy the generated file where the m2 snippet reads it, refusing to start without it', () => {
    expect(service(compose, 'caddy')).toContain(
      [
        '      - type: bind',
        `        source: ./${CADDY_PUBLIC_PATH.replace(/^deploy\//, '')}`,
        `        target: ${CADDY_PUBLIC_MOUNT}`,
        '        read_only: true',
        '        bind:',
        '          create_host_path: false',
      ].join('\n'),
    )
  })
})
