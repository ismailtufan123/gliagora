import { readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import {
  BRAND_PREFIX,
  HERO_PREFIX,
  type IsDraft,
  NEXT_STATIC_PREFIX,
  PUBLIC_MARK,
  publicMachineFiles,
  publicPages,
} from '../lib/public-pages'

// deploy/caddy/m2-public.caddy, written from src/lib/public-pages.ts by `pnpm caddy:public`
// (src/scripts/caddy-public.ts): the addresses the M2 state opens without the site-wide password
// (D41, D50). A unit test fails when the file in the repository is out of date. Relative imports
// only, like the list itself.

/** The file, as the repository names it. */
export const CADDY_PUBLIC_PATH = 'deploy/caddy/m2-public.caddy'
export const CADDY_PUBLIC_FILE = fileURLToPath(
  new URL('../../deploy/caddy/m2-public.caddy', import.meta.url),
)

/** Where Caddy reads it on the server (deploy/compose.prod.yml mounts it there). */
export const CADDY_PUBLIC_MOUNT = '/etc/caddy/m2-public.caddy'

/** The logos and the favicon, the files Caddy opens under /brand/, from the folder. */
export const BRAND_FOLDER = fileURLToPath(new URL('../../public/brand/', import.meta.url))
export const brandFiles = (): string[] =>
  readdirSync(BRAND_FOLDER, { withFileTypes: true })
    .filter((entry) => entry.isFile() && !entry.name.startsWith('.'))
    .map((entry) => `${BRAND_PREFIX}${entry.name}`)
    .sort()

/** The 3D hero's point file (M13), the files Caddy opens under /hero/, from the folder. */
export const HERO_FOLDER = fileURLToPath(new URL('../../public/hero/', import.meta.url))
export const heroFiles = (): string[] =>
  readdirSync(HERO_FOLDER, { withFileTypes: true })
    .filter((entry) => entry.isFile() && !entry.name.startsWith('.'))
    .map((entry) => `${HERO_PREFIX}${entry.name}`)
    .sort()

const HEADER = `# Generated by \`pnpm caddy:public\` from src/lib/public-pages.ts: do not edit it by hand. A unit
# test fails when it is out of date (src/scripts/caddy-public.test.ts).
#
# What the M2 state (SITE_STAGE=m2, D41, D50) opens without the site-wide password: the
# Caddyfile's \`stage-m2\` snippet imports this file before the site's catch-all, which keeps every
# other address behind the password. Only the pages that are public now: a legal text joins the
# list once the operator has approved it (draft: false), and the file must then be written again
# and copied to the server (deploy/README.md, "Switching to the M2 state").
#
# Each matcher names its addresses twice. \`path\` lists them for people to read (each page with
# and without its trailing slash, which Next.js redirects to; Next.js's own files by prefix; each
# logo in public/brand/ and the hero's point file in public/hero/), but Caddy compares those after
# decoding them and without regard to case,
# while the app does neither. So the regexp on the raw address ({http.request.uri}, still encoded,
# with its query) lets only their exact spelling through, with any query: /EN/, /en/%61bout/ or
# /en/x/../about/ keep the password. A request to a page, a machine file or a form goes to the app
# with the mark ${PUBLIC_MARK.name}, and the app refuses it when the running image does not hold
# that address public (src/lib/public-pages.ts, PUBLIC_MARK). Then the app's answer: a 404 or 410
# becomes a plain "Not Found" with the same status (never the app's 404 page, which has the full
# navigation), and an answer to a page, a machine file or a form without the app's mark (an image
# that knows no M2 state) a plain 404; redirects pass. The site's headers and log filters apply
# here too.
`

/** A regular expression's special characters, escaped (Go's RE2, which Caddy uses, and JS alike). */
const escape = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

/** Next.js's own files: one or more path segments of safe characters, none of them `.` or `..`. */
export const NEXT_STATIC_PATTERN = `${escape(NEXT_STATIC_PREFIX.slice(0, -1))}(?:/[A-Za-z0-9_~-][A-Za-z0-9._~-]*)+`

/**
 * The regexp Caddy matches against the raw request address: exactly these paths (and Next.js's own
 * files with `nextStatic`), each with any query string or none.
 */
export function rawAddressPattern(paths: readonly string[], nextStatic = false): string {
  const alternatives = [...paths.map(escape), ...(nextStatic ? [NEXT_STATIC_PATTERN] : [])]
  return `^(?:${alternatives.join('|')})(?:\\?.*)?$`
}

/** The page's address in both spellings, as the app answers them (without the slash: a redirect). */
const spellings = (path: string) => (path === '/' ? [path] : [path.slice(0, -1), path])

/** The app's 404s and 410s, as a plain text: never the app's 404 page with its navigation. */
const PLAIN_MISSING = [
  '\t\t@missing status 404 410',
  '\t\thandle_response @missing {',
  '\t\t\trespond "Not Found" {rp.status_code}',
  '\t\t}',
]

/** Answers the app did not mark as its own public ones: a plain 404 (redirects pass). */
const ONLY_MARKED = [
  '\t\t@unmarked {',
  '\t\t\tstatus 2xx 4xx 5xx',
  `\t\t\theader !${PUBLIC_MARK.name}`,
  '\t\t}',
  '\t\thandle_response @unmarked {',
  '\t\t\trespond "Not Found" 404',
  '\t\t}',
]

type Block = {
  name: string
  methods: string
  /** The `path` lines: one per page (both spellings) or file, one for Next.js's files. */
  lines: string[]
  pattern: string
  /** Pages, machine files and forms: the requests are marked, and only marked answers pass. */
  marked: boolean
}

/** One named matcher with its handle, which passes the request to the app without the password. */
function block({ name, methods, lines, pattern, marked }: Block): string {
  return [
    `@${name} {`,
    `\tmethod ${methods}`,
    ...lines.map((line) => `\tpath ${line}`),
    `\tvars_regexp {http.request.uri} ${pattern}`,
    '}',
    `handle @${name} {`,
    ...(marked ? [`\trequest_header ${PUBLIC_MARK.name} ${PUBLIC_MARK.value}`] : []),
    '\treverse_proxy app:3000 {',
    ...PLAIN_MISSING,
    ...(marked ? ONLY_MARKED : []),
    '\t}',
    '}',
  ].join('\n')
}

/**
 * The file's text for the approvals given (today's by default), the logos in public/brand/ and the
 * hero's point file in public/hero/.
 */
export function m2PublicCaddy(
  draft?: IsDraft,
  brand: readonly string[] = brandFiles(),
  hero: readonly string[] = heroFiles(),
): string {
  const pages = publicPages(draft)
  const get = [
    ...pages.map((page) => spellings(page.path)),
    ...publicMachineFiles(draft).map((file) => [file]),
  ]
  const post = pages.filter((page) => page.post).map((page) => spellings(page.path))
  return [
    HEADER,
    block({
      name: 'm2Public',
      methods: 'GET HEAD',
      lines: get.map((paths) => paths.join(' ')),
      pattern: rawAddressPattern(get.flat()),
      marked: true,
    }),
    '',
    block({
      name: 'm2PublicFiles',
      methods: 'GET HEAD',
      lines: [`${NEXT_STATIC_PREFIX}*`, ...brand, ...hero],
      pattern: rawAddressPattern([...brand, ...hero], true),
      marked: false,
    }),
    // Only while a form is public: Caddy refuses a matcher without paths.
    ...(post.length > 0
      ? [
          '',
          block({
            name: 'm2PublicPost',
            methods: 'POST',
            lines: post.map((paths) => paths.join(' ')),
            pattern: rawAddressPattern(post.flat()),
            marked: true,
          }),
        ]
      : []),
    '',
  ].join('\n')
}
