import { readdirSync, readFileSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

// PLAN §7, §17.2: colours come only from the design tokens in tokens.css.
const here = path.dirname(fileURLToPath(import.meta.url))
const src = path.resolve(here, '../..')
const tokensFile = path.join(here, 'tokens.css')
// The browser theme colour must be a literal in the page metadata; the last test below checks it
// equals the --bg tokens. It is the only allowed exception, in this one file.
const metadataFile = path.join(src, 'lib', 'metadata.ts')
const THEME_COLOUR =
  /^\s*\{ media: '\(prefers-color-scheme: (light|dark)\)', color: '#[0-9a-f]{6}' \},$/i

const RAW_COLOUR = /#[0-9a-f]{3,8}\b|\b(?:rgba?|hsla?|oklch|oklab|lab|lch)\(/i
const SKIP = [
  path.join(src, 'app', '(payload)'), // generated by Payload
  path.join(src, 'migrations'),
  path.join(src, 'payload-types.ts'),
  tokensFile,
]

function files(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name)
    if (SKIP.some((skip) => full === skip || full.startsWith(skip + path.sep))) return []
    if (statSync(full).isDirectory()) return files(full)
    return /\.(css|tsx?)$/.test(name) && !/\.test\.tsx?$/.test(name) ? [full] : []
  })
}

function tokenValue(name: string, dark: boolean): string {
  const css = readFileSync(tokensFile, 'utf8')
  const darkStart = css.indexOf('@media (prefers-color-scheme: dark)')
  const block = dark ? css.slice(darkStart) : css.slice(0, darkStart)
  const match = new RegExp(`--${name}:\\s*(#[0-9a-f]{6});`, 'i').exec(block)
  if (!match?.[1]) throw new Error(`--${name} not found`)
  return match[1].toLowerCase()
}

describe('raw colour values', () => {
  it('appear nowhere outside tokens.css (except the browser theme colour)', () => {
    const offenders = files(src).flatMap((file) =>
      readFileSync(file, 'utf8')
        .split('\n')
        .map((line, i) => ({ line, at: `${path.relative(src, file)}:${i + 1}` }))
        .filter(({ line }) => RAW_COLOUR.test(line))
        .filter(({ line }) => !(file === metadataFile && THEME_COLOUR.test(line)))
        .map(({ at, line }) => `${at}: ${line.trim()}`),
    )
    expect(offenders).toEqual([])
  })

  it('uses the --bg tokens as the browser theme colour', () => {
    const layout = readFileSync(metadataFile, 'utf8')
    const themeColours = [...layout.matchAll(/color: '(#[0-9a-f]{6})'/gi)].map((m) =>
      m[1]!.toLowerCase(),
    )
    expect(themeColours).toEqual([tokenValue('bg', false), tokenValue('bg', true)])
  })
})
